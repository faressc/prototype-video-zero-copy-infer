static void on_global(void* data,
                      struct wl_registry* registry,
                      uint32_t name,
                      const char* interface,
                      uint32_t version) {
    struct state* st = data;

    if (strcmp(interface, wl_compositor_interface.name) == 0) {
        /* v4: needed for wl_surface.damage_buffer below */
        st->compositor = wl_registry_bind(registry, name, &wl_compositor_interface, 4);
    } else if (strcmp(interface, wl_shm_interface.name) == 0) {
        st->shm = wl_registry_bind(registry, name, &wl_shm_interface, 1);
    } else if (strcmp(interface, xdg_wm_base_interface.name) == 0) {
        st->wm_base = wl_registry_bind(registry, name, &xdg_wm_base_interface, 1);
    } else if (strcmp(interface, wl_seat_interface.name) == 0) {
        /* First real use of the version argument: negotiate
         * min(server, what we implement). v5 pointer objects batch
         * events into frames (see on_pointer_frame). */
        st->seat = wl_registry_bind(registry, name, &wl_seat_interface, version < 5 ? version : 5);
    }
}

static void on_global_remove(void* data, struct wl_registry* registry, uint32_t name) {
    (void)data;
    (void)registry;
    (void)name;
}

