static void on_keyboard_key(void* data,
                            struct wl_keyboard* keyboard,
                            uint32_t serial,
                            uint32_t time,
                            uint32_t key,
                            uint32_t key_state) {
    (void)keyboard;
    (void)serial;
    (void)time;
    struct state* st = data;

    if (key_state != WL_KEYBOARD_KEY_STATE_PRESSED || !st->xkb_state) { return; }

    /* wl_keyboard delivers evdev scancodes; xkb keycodes are evdev + 8
     * (a fossilized X11 offset). */
    xkb_keysym_t sym = xkb_state_key_get_one_sym(st->xkb_state, key + 8);
    switch (sym) {
        case XKB_KEY_Escape:
        case XKB_KEY_q: st->running = 0; break;
        case XKB_KEY_space: st->paused = !st->paused; break;
        default: break;
    }
}

static void on_keyboard_modifiers(void* data,
                                  struct wl_keyboard* keyboard,
                                  uint32_t serial,
                                  uint32_t mods_depressed,
                                  uint32_t mods_latched,
                                  uint32_t mods_locked,
                                  uint32_t group) {
    (void)keyboard;
    (void)serial;
    struct state* st = data;

    /* Feed modifier state to xkb so Shift+q still means 'Q' etc. */
    if (st->xkb_state) {
        xkb_state_update_mask(st->xkb_state,
                              mods_depressed,
                              mods_latched,
                              mods_locked,
                              0,
                              0,
                              group);
    }
}

