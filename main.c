/* ------------------------------------------------------------------ */
/* Input, part 1: the keyboard.                                       */
/*                                                                    */
/* Wayland deliberately sends RAW scancodes -- interpreting them      */
/* needs the keymap, and the keymap arrives as... a file descriptor.  */
/* The same trick as our pixel buffers, in the other direction: the   */
/* compositor shares one memfd holding the xkb keymap text and every  */
/* client maps the same copy. xkbcommon compiles it and translates    */
/* scancode -> keysym, honoring layout and modifiers.                 */
/* ------------------------------------------------------------------ */

static void on_keyboard_keymap(void* data,
                               struct wl_keyboard* keyboard,
                               uint32_t format,
                               int32_t fd,
                               uint32_t size) {
    (void)keyboard;
    struct state* st = data;

    if (format != WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1) {
        close(fd);
        return;
    }

    char* map = mmap(NULL, size, PROT_READ, MAP_PRIVATE, fd, 0);
    if (map == MAP_FAILED) {
        close(fd);
        return;
    }

    /* Keymaps can change at runtime (layout switch) -> replace, not set. */
    xkb_state_unref(st->xkb_state);
    xkb_keymap_unref(st->xkb_keymap);
    st->xkb_keymap = xkb_keymap_new_from_string(st->xkb_context,
                                                map,
                                                XKB_KEYMAP_FORMAT_TEXT_V1,
                                                XKB_KEYMAP_COMPILE_NO_FLAGS);
    st->xkb_state = st->xkb_keymap ? xkb_state_new(st->xkb_keymap) : NULL;

    munmap(map, size);
    close(fd);
}

