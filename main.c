enum { WIDTH = 640, HEIGHT = 360 }; /* fallback size when the compositor has no opinion */

/* Double buffering: one buffer on screen, one being drawn. Bump to 3
 * (triple buffering) if a compositor ever holds buffers long enough
 * that render() has to skip frames. */
enum { SLOTS = 1 };

struct slot {
    struct wl_buffer* buffer; /* this slot's CURRENT protocol object */
    int busy;                 /* committed and not yet released by the compositor */
};

/* One batched pointer transaction (seat v5+). The wl_pointer event
 * handlers only STAGE fields here; wl_pointer.frame APPLIES them as
 * one atomic update -- the same stage/apply discipline as surface
 * commit and configure/ack, now in the input direction. */
enum {
    PTR_MOTION = 1 << 0, /* x/y valid (enter or motion) */
    PTR_BUTTON = 1 << 1, /* button/button_state/serial valid */
    PTR_AXIS_V = 1 << 2, /* axis_v valid */
};

struct pointer_event {
    uint32_t mask;         /* which of the fields this frame touched */
    double x, y;           /* latest position within the frame */
    uint32_t button;       /* evdev button code (BTN_LEFT, ...) */
    uint32_t button_state; /* pressed or released */
    uint32_t serial;       /* of the button event -- authorizes moves */
    double axis_v;         /* vertical scroll, summed over the frame */
};

struct state {
    /* connection + introduction phase */
    struct wl_display* display;
    struct wl_registry* registry;
    struct wl_compositor* compositor;
    struct wl_shm* shm;          /* shared-memory buffers (simplest kind) */
    struct xdg_wm_base* wm_base; /* the "make surfaces into windows" service */

    /* the window itself */
    struct wl_surface* surface;
    struct xdg_surface* xdg_surface;
    struct xdg_toplevel* toplevel;

    /* input: one seat = one user (pointer + keyboard + touch caps) */
    struct wl_seat* seat;
    struct wl_pointer* pointer;
    struct wl_keyboard* keyboard;
    struct xkb_context* xkb_context;
    struct xkb_keymap* xkb_keymap;
    struct xkb_state* xkb_state;
    double ptr_x, ptr_y;            /* last APPLIED pointer position */
    struct pointer_event ptr_event; /* the staged, not-yet-applied batch */

    /* The cursor: one more wl_surface with one more (theme-provided)
     * shm buffer. We commit it once; the compositor moves it. */
    struct wl_cursor_theme* cursor_theme;
    struct wl_surface* cursor_surface;
    struct wl_cursor_image* cursor_image; /* kept for the hotspot */

    /* Pixel storage: ONE pool holding SLOTS buffers side by side,
     * recreated only when the size changes. Steady-state animation
     * allocates nothing -- the slots ping-pong forever. */
    struct wl_shm_pool* pool;
    uint32_t* pool_data; /* our mapping of the whole pool */
    size_t pool_bytes;
    struct slot slots[SLOTS];
    int buf_w, buf_h; /* size the slot buffers are currently created at */

    /* Window size. STAGED by xdg_toplevel.configure (data, no serial),
     * CONSUMED when we ack in xdg_surface.configure (serial, no data).
     * The compositor sends 0 for "you pick" -> fall back to WIDTH/HEIGHT. */
    int pending_w;
    int pending_h;

    uint32_t last_time; /* timestamp (ms) of the last frame callback */
    double anim_ms;     /* animation clock: pausable and speed-scalable */
    double speed;       /* scroll wheel adjusts; negative runs backwards */
    int paused;         /* Space toggles */
    int animating;      /* frame-callback loop started? */
    int running;
};

