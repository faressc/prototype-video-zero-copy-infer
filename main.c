/* ------------------------------------------------------------------ */
/* Input, part 2: the pointer.                                        */
/*                                                                    */
/* Coordinates are surface-local, as wl_fixed_t (24.8 fixed point).   */
/* Since v5 the events are BATCHED: enter/motion/axis... describe one */
/* hardware event together and wl_pointer.frame terminates the batch. */
/* The handlers below therefore only STAGE into st->ptr_event; all    */
/* application state changes happen in on_pointer_frame. This is what */
/* keeps a diagonal touchpad scroll (two axis events, one frame) one  */
/* gesture instead of an L-shaped pair.                               */
/* ------------------------------------------------------------------ */

static void on_pointer_enter(void* data,
                             struct wl_pointer* pointer,
                             uint32_t serial,
                             struct wl_surface* surface,
                             wl_fixed_t sx,
                             wl_fixed_t sy) {
    (void)surface;
    struct state* st = data;

    /* STAGE the entry position; applied in on_pointer_frame. */
    st->ptr_event.mask |= PTR_MOTION;
    st->ptr_event.x = wl_fixed_to_double(sx);
    st->ptr_event.y = wl_fixed_to_double(sy);

    /* set_cursor is NOT application state, it is the protocol reply to
     * this enter (like pong answers ping), quoting the enter serial --
     * so it does not wait for the frame event. */

    /* Inside our window the cursor image is OUR responsibility -- the
     * compositor draws no default. We hand it our cursor surface plus
     * the HOTSPOT: which pixel of the image is the logical tip (an
     * arrow points top-left, a crosshair centers). The serial proves
     * we answer THIS enter, not a stale one. NULL would hide the
     * cursor; cursor-shape-v1 is the modern way to skip all of this
     * and name a shape for the compositor to draw. */
    if (st->cursor_surface) {
        wl_pointer_set_cursor(pointer,
                              serial,
                              st->cursor_surface,
                              (int32_t)st->cursor_image->hotspot_x,
                              (int32_t)st->cursor_image->hotspot_y);
    } else {
        wl_pointer_set_cursor(pointer, serial, NULL, 0, 0);
    }
}

static void on_pointer_leave(void* data,
                             struct wl_pointer* pointer,
                             uint32_t serial,
                             struct wl_surface* surface) {
    (void)data;
    (void)pointer;
    (void)serial;
    (void)surface;
}

static void on_pointer_motion(void* data,
                              struct wl_pointer* pointer,
                              uint32_t time,
                              wl_fixed_t sx,
                              wl_fixed_t sy) {
    (void)pointer;
    (void)time;
    struct state* st = data;

    /* STAGE only -- multiple fields of one hardware event (motion +
     * axis of a touchpad gesture) must land together, at the frame. */
    st->ptr_event.mask |= PTR_MOTION;
    st->ptr_event.x = wl_fixed_to_double(sx);
    st->ptr_event.y = wl_fixed_to_double(sy);
}

static void on_pointer_button(void* data,
                              struct wl_pointer* pointer,
                              uint32_t serial,
                              uint32_t time,
                              uint32_t button,
                              uint32_t button_state) {
    (void)pointer;
    (void)time;
    struct state* st = data;

    /* STAGE. Two buttons in one frame would overwrite each other --
     * a real toolkit keeps a small list; one is plenty here. */
    st->ptr_event.mask |= PTR_BUTTON;
    st->ptr_event.button = button;
    st->ptr_event.button_state = button_state;
    st->ptr_event.serial = serial;
}

static void on_pointer_axis(void* data,
                            struct wl_pointer* pointer,
                            uint32_t time,
                            uint32_t axis,
                            wl_fixed_t value) {
    (void)pointer;
    (void)time;
    struct state* st = data;

    if (axis == WL_POINTER_AXIS_VERTICAL_SCROLL) {
        /* STAGE, and SUM: one frame may carry several axis events. */
        st->ptr_event.mask |= PTR_AXIS_V;
        st->ptr_event.axis_v += wl_fixed_to_double(value);
    }
}

/* End of one batched pointer transaction: APPLY the staged fields as
 * a single atomic update, then clear the staging area. (Pre-v5 servers
 * never send frame; a fully portable app applies after every event
 * when wl_pointer_get_version() < 5 -- omitted here, we bind v5.) */
static void on_pointer_frame(void* data, struct wl_pointer* pointer) {
    (void)pointer;
    struct state* st = data;
    struct pointer_event* ev = &st->ptr_event;

    if (ev->mask & PTR_MOTION) {
        st->ptr_x = ev->x;
        st->ptr_y = ev->y;
    }

    if ((ev->mask & PTR_BUTTON) && ev->button == BTN_LEFT &&
        ev->button_state == WL_POINTER_BUTTON_STATE_PRESSED) {
        /* Hand the drag to the compositor. The serial is the key: it
         * proves we act on FRESH user input -- the compositor honors
         * move/resize only against a recent input serial, so apps
         * cannot fling windows around spontaneously. */
        xdg_toplevel_move(st->toplevel, st->seat, ev->serial);
    }

    if (ev->mask & PTR_AXIS_V) {
        /* scroll up = faster, down = slower; through zero into reverse */
        st->speed -= ev->axis_v / 20.0;
        if (st->speed > 10.0) { st->speed = 10.0; }
        if (st->speed < -10.0) { st->speed = -10.0; }
    }

    memset(ev, 0, sizeof(*ev)); /* transaction consumed */
}

